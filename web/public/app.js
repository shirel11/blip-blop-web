function sendKey(key, down) {
  const code = key.startsWith('Arrow')
    ? key
    : key === ' '
      ? 'Space'
      : key.length === 1
        ? 'Key' + key.toUpperCase()
        : key;
  canvas.dispatchEvent(
    new KeyboardEvent(down ? 'keydown' : 'keyup', {
      key,
      code,
      keyCode: keyCodes[key],
      which: keyCodes[key],
      bubbles: true,
      cancelable: true,
    }),
  );
}
function reconcileKeys() {
  const next = new Set();
  for (const p of pointers.values()) for (const k of p.keys) next.add(k);
  for (const k of heldKeys) if (!next.has(k)) sendKey(k, false);
  for (const k of next) if (!heldKeys.has(k)) sendKey(k, true);
  heldKeys.clear();
  for (const k of next) heldKeys.add(k);
  document.querySelectorAll('[data-key], [data-direction]').forEach((b) => {
    const pressed = next.has(b.dataset.key || b.dataset.direction);
    b.classList.toggle('pressed', pressed);
    b.setAttribute('aria-pressed', String(pressed));
  });
}
function releaseAll() {
  pointers.clear();
  reconcileKeys();
  // Also release physical keys in SDL when the tab loses focus.
  for (const key of Object.keys(keyCodes)) sendKey(key, false);
}
function endPointer(e, cancelled = false) {
  const entry = pointers.get(e.pointerId);
  if (!entry || entry.releasing) return;
  entry.releasing = true;
  const delay = cancelled
    ? 0
    : Math.max(0, 90 - (performance.now() - entry.started));
  setTimeout(() => {
    if (pointers.get(e.pointerId) === entry) {
      pointers.delete(e.pointerId);
      reconcileKeys();
    }
  }, delay);
}
document.querySelectorAll('[data-key]').forEach((button) => {
  button.addEventListener('pointerdown', (e) => {
    e.preventDefault();
    if (phase !== 'running') return;
    button.setPointerCapture(e.pointerId);
    pointers.set(e.pointerId, {
      keys: [button.dataset.key],
      started: performance.now(),
    });
    reconcileKeys();
  });
  button.addEventListener('pointerup', (e) => endPointer(e));
  button.addEventListener('pointercancel', (e) => endPointer(e, true));
  button.addEventListener('lostpointercapture', (e) => endPointer(e));
});
const pad = $('#dpad');
function padKeys(e) {
  const r = pad.getBoundingClientRect();
  const x = (e.clientX - r.left - r.width / 2) / (r.width / 2);
  const y = (e.clientY - r.top - r.height / 2) / (r.height / 2);
  const keys = [];
  if (x < -0.28) keys.push('ArrowLeft');
  if (x > 0.28) keys.push('ArrowRight');
  if (y < -0.28) keys.push('ArrowUp');
  if (y > 0.28) keys.push('ArrowDown');
  return keys;
}
pad.addEventListener('pointerdown', (e) => {
  e.preventDefault();
  if (phase !== 'running') return;
  pad.setPointerCapture(e.pointerId);
  pointers.set(e.pointerId, { keys: padKeys(e), started: performance.now() });
  reconcileKeys();
});
pad.addEventListener('pointermove', (e) => {
  const p = pointers.get(e.pointerId);
  if (p && !p.releasing) {
    p.keys = padKeys(e);
    reconcileKeys();
  }
});
pad.addEventListener('pointerup', (e) => endPointer(e));
pad.addEventListener('pointercancel', (e) => endPointer(e, true));
pad.addEventListener('lostpointercapture', (e) => endPointer(e));
// Direction buttons remain operable by keyboard assistive input as well.
pad.querySelectorAll('button').forEach((b) =>
  b.addEventListener('click', (e) => {
    if (e.detail === 0 && phase === 'running') pulseKey(b.dataset.direction);
  }),
);
function pulseKey(key) {
  sendKey(key, true);
  setTimeout(() => sendKey(key, false), 130);
}

function fail(key, error) {
  phase = 'error';
  statusKey = key;
  packageBuffer = null;
  $('#start').disabled = false;
  $('#progress').hidden = true;
  $('#cover').hidden = false;
  if (error) console.error(error);
  renderStatus();
}
window.Module = {
  canvas,
  noInitialRun: true,
  locateFile: (name) =>
    new URL(
      './resources/' + (name === 'game.wasm' ? 'game-v2.wasm' : name),
      location.href,
    ).href,
  print: () => {},
  printErr: (message) => {
    lastEngineError = String(message);
    console.warn(message);
  },
  onAbort: () => fail('engineError'),
  onRuntimeInitialized() {
    engineReady = true;
    phase = 'ready';
    statusKey = 'ready';
    $('#start').disabled = false;
    $('#progress').hidden = true;
    renderStatus();
  },
};
async function downloadPackage(signal) {
  const response = await fetch('./resources/game.data.gz', { signal });
  if (!response.ok || !response.body)
    throw new Error(`Asset download: HTTP ${response.status}`);
  const total = Number(response.headers.get('Content-Length')) || 53213133;
  let received = 0;
  let lastStatus = 0;
  const meter = new TransformStream({
    transform(chunk, controller) {
      received += chunk.byteLength;
      if (performance.now() - lastStatus > 150) {
        statusKey = 'downloading';
        downloadMB = (received / 1048576).toFixed(1);
        $('#progress').value = Math.min(97, (received / total) * 97);
        renderStatus();
        lastStatus = performance.now();
      }
      controller.enqueue(chunk);
    },
  });
  // Stream compressed bytes straight into the decoder. No chunks array, Blob,
  // or second compressed copy during Safari's memory-sensitive startup.
  return new Response(
    response.body
      .pipeThrough(meter)
      .pipeThrough(new DecompressionStream('gzip')),
  ).arrayBuffer();
}
function normalizeTextAssets() {
  for (const name of Module.FS.readdir('/data')) {
    if (name.endsWith('.lst') || name.endsWith('.rpg')) {
      const path = '/data/' + name;
      Module.FS.writeFile(
        path,
        Module.FS.readFile(path, { encoding: 'utf8' }).replace(/\r\n/g, '\n'),
      );
    }
  }
}
$('#start').onclick = async () => {
  if (phase === 'loading' || phase === 'running') return;
  if (engineReady) {
    phase = 'running';
    $('#cover').hidden = true;
    document.body.classList.add('running');
    $('#pause').disabled = false;
    canvas.focus({ preventScroll: true });
    try {
      normalizeTextAssets();
      Module.callMain([]);
    } catch (e) {
      if (e !== 'unwind' && e?.status !== 0)
        fail('engineError', lastEngineError || e);
    }
    return;
  }
  if (
    !('WebAssembly' in window) ||
    !('DecompressionStream' in window) ||
    !('TransformStream' in window)
  ) {
    fail('unsupported');
    return;
  }
  const generation = ++loadGeneration;
  downloadController?.abort();
  downloadController = new AbortController();
  phase = 'loading';
  statusKey = 'connecting';
  downloadMB = '';
  $('#start').disabled = true;
  $('#progress').hidden = false;
  $('#progress').value = 0;
  renderStatus();
  try {
    packageBuffer = await downloadPackage(downloadController.signal);
    if (generation !== loadGeneration) return;
    statusKey = 'initializing';
    renderStatus();
    Module.getPreloadedPackage = () => {
      const buffer = packageBuffer;
      packageBuffer = null;
      return buffer;
    };
    const script = document.createElement('script');
    script.src = './engine-v2.js';
    script.onerror = () => fail('loadError');
    document.body.append(script);
  } catch (error) {
    if (error.name !== 'AbortError') fail('loadError', error);
  }
};
